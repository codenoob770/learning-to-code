# LESSON 3 - Boxes with names
#
# Run it:   python3 lessons/03_boxes.py


# You can put something in a box and give the box a name.
# The = sign means: put this in the box.

name = "Sam"
age = 25

# Now use the box name anywhere you like.
print(name)
print(age)


# You can put a new thing in a box. The old thing is gone.
age = 26
print(age)


# You can do maths with boxes.
price = 3
count = 4
print(price * count)          # 12


# To mix words and boxes in one sentence:
# put an f just before the quotes, and put box names in curly brackets.
print(f"{name} is {age} years old")


# The proper word for a box is a "variable". Same thing. Don't worry about it.


