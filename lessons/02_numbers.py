# Words go in quotes. Numbers do not need quotes.
print(5)

# The computer will do the maths for you.
print(2 + 2)
print(10 - 4)
print(6 * 3)      # a star means times
print(10 / 2)     # a slash means divided by


# Watch what the quotes do:
print(2 + 2)      # no quotes, so it works it out:     4
print("2 + 2")    # quotes mean words, so it copies:   2 + 2


